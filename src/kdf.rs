    /// A byte modified **anywhere** must make opening fail, in particular in
    /// the header: that is what prevents bringing the number of iterations
    /// down to one.
    #[test]
    fn a_modified_byte_makes_opening_fail() {
        // The test cost: this test performs one derivation per byte of the
        // sealed output, and it is the property being checked, not the cost
        // of the derivation.
        let s = seal(b"passphrase", b"well-kept secret", TEST_COST).unwrap();
        for pos in 0..s.len() {
            let mut altered = s.clone();
            altered[pos] ^= 0x01;
            assert!(
                unseal(b"passphrase", &altered).is_err(),
                "byte {pos} could be modified without being detected"
            );
        }
    }

