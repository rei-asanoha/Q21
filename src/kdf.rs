    /// A sealed file in format 1 (PBKDF2) still opens: nobody must lose
    /// access to their wallet because the derivation changed. It is
    /// recognized as old, so that it gets resealed.
    #[test]
    fn a_seal_in_the_old_format_still_opens() {
        // Exact reproduction of the format 1 `seal`, with a fixed salt.
        let passphrase = b"passphrase from before";
        let plaintext = b"seed=deadbeef\nnext_index=3\n";
        let iterations = 1_000u32;
        let salt = [7u8; 16];
        let k = derive_pbkdf2(passphrase, &salt, iterations);
        let mut old = Vec::new();
        old.extend_from_slice(MAGIC_V1);
        old.extend_from_slice(&iterations.to_le_bytes());
        old.extend_from_slice(&salt);
        let start = old.len();
        old.extend_from_slice(plaintext);
        keystream_xor(
            crate::legacy::LEGACY_KEYSTREAM_LABEL,
            &k.encryption,
            &mut old[start..],
        );
        let mac = hmac_sha256(&k.authentication, &old);
        old.extend_from_slice(&mac);

        assert!(is_sealed(&old));
        assert!(is_legacy_format(&old));
        assert_eq!(unseal(passphrase, &old).unwrap(), plaintext);
        assert!(unseal(b"other", &old).is_err());

        // And the current format is not "old".
        let new = seal(passphrase, plaintext, TEST_COST).unwrap();
        assert!(is_sealed(&new));
        assert!(!is_legacy_format(&new));
        assert_eq!(unseal(passphrase, &new).unwrap(), plaintext);
    }

    /// A wallet sealed by 0.3.x (format 2: Argon2id, legacy keystream label)
    /// still opens, and what is sealed now is format 3. Moving a file from one
    /// format to the other by rewriting its magic fails: the MAC covers it.
    #[test]
    fn a_seal_in_format_2_still_opens_and_new_seals_are_format_3() {
        let passphrase = b"passphrase from 0.3";
        let plaintext = b"seed=deadbeef\nnext_index=3\nserial=4\n";
        let salt = [9u8; 16];
        let k = derive_argon2(passphrase, &salt, TEST_COST);
        let mut v2 = Vec::new();
        v2.extend_from_slice(MAGIC_V2);
        v2.extend_from_slice(&TEST_COST.memory_kib.to_le_bytes());
        v2.extend_from_slice(&TEST_COST.passes.to_le_bytes());
        v2.extend_from_slice(&salt);
        let start = v2.len();
        v2.extend_from_slice(plaintext);
        keystream_xor(
            crate::legacy::LEGACY_KEYSTREAM_LABEL,
            &k.encryption,
            &mut v2[start..],
        );
        let mac = hmac_sha256(&k.authentication, &v2);
        v2.extend_from_slice(&mac);

        assert!(is_sealed(&v2));
        assert!(!is_legacy_format(&v2));
        assert_eq!(stored_cost(&v2), Some(TEST_COST));
        assert_eq!(unseal(passphrase, &v2).unwrap(), plaintext);
        assert_eq!(unseal(b"other", &v2), Err(SealError::AuthenticationFailed));

        let v3 = seal(passphrase, plaintext, TEST_COST).unwrap();
        assert_eq!(&v3[..8], MAGIC_V3);
        assert_eq!(stored_cost(&v3), Some(TEST_COST));
        assert_eq!(unseal(passphrase, &v3).unwrap(), plaintext);

        let mut relabeled = v2.clone();
        relabeled[..8].copy_from_slice(MAGIC_V3);
        assert_eq!(
            unseal(passphrase, &relabeled),
            Err(SealError::AuthenticationFailed)
        );
        let mut relabeled = v3.clone();
        relabeled[..8].copy_from_slice(MAGIC_V2);
        assert_eq!(
            unseal(passphrase, &relabeled),
            Err(SealError::AuthenticationFailed)
        );
    }

    /// The two keystream labels give two different streams: a file sealed
    /// under one cannot be read under the other.
    #[test]
    fn the_two_keystream_labels_differ() {
        let key = [3u8; 32];
        let mut a = [0u8; 64];
        let mut b = [0u8; 64];
        keystream_xor(KEYSTREAM_LABEL, &key, &mut a);
        keystream_xor(crate::legacy::LEGACY_KEYSTREAM_LABEL, &key, &mut b);
        assert_ne!(a, b);
    }

    /// A cost rewritten in the header is refused before any derivation: an
    /// attacker who writes eight bytes must not be able to impose a gibibyte
    /// of computation before any rejection.
    #[test]
    fn an_out_of_range_cost_is_refused_before_deriving() {
        let s = seal(b"passphrase", b"secret", TEST_COST).unwrap();
        let mut memory = s.clone();
        memory[8..12].copy_from_slice(&u32::MAX.to_le_bytes());
        let t = std::time::Instant::now();
        assert!(matches!(
            unseal(b"passphrase", &memory),
            Err(SealError::CostOutOfRange { .. })
        ));
        assert!(t.elapsed() < std::time::Duration::from_millis(50));

        let mut passes = s.clone();
        passes[12..16].copy_from_slice(&1_000u32.to_le_bytes());
        assert!(matches!(
            unseal(b"passphrase", &passes),
            Err(SealError::CostOutOfRange { .. })
        ));
    }

